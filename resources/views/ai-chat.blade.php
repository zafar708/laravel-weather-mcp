        <main id="messages" class="flex-1 space-y-6 overflow-y-auto px-4 py-6 sm:px-8" aria-live="polite">
            <section id="welcome" class="mx-auto mt-12 max-w-lg text-center">
                <div class="mx-auto mb-4 flex size-14 items-center justify-center rounded-2xl bg-violet-50 text-2xl text-violet-600">
                    ✦
                </div>
                <h2 class="text-xl font-semibold">Ask me anything</h2>
                <p class="mt-2 text-sm leading-6 text-slate-500">
                    I can check live weather, rain forecasts, and the sample users. Each tool I use is shown under my reply.
                </p>

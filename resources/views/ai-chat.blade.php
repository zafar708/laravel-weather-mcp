        <form id="chat-form" class="border-t border-slate-200 bg-white px-4 py-4 sm:px-8">
            <label for="message" class="sr-only">Your message</label>
            <div class="flex items-end gap-3 rounded-2xl border border-slate-300 bg-white p-2 shadow-sm transition focus-within:border-violet-400 focus-within:ring-4 focus-within:ring-violet-100">
                <textarea id="message" name="message" rows="1" maxlength="1000" required
                          placeholder="Ask about weather, rain, or the sample users..."
                          class="max-h-32 min-h-11 flex-1 resize-y border-0 bg-transparent px-3 py-2.5 text-sm outline-none placeholder:text-slate-400"
                          aria-describedby="chat-hint"></textarea>
                <button id="send-button" type="submit"
                        class="inline-flex h-11 shrink-0 items-center justify-center rounded-xl bg-violet-600 px-4 text-sm font-medium text-white transition hover:bg-violet-700 focus:outline-none focus:ring-4 focus:ring-violet-200 disabled:cursor-not-allowed disabled:bg-slate-300">
                    Send
                </button>
            </div>
            <p id="chat-hint" class="mt-2 text-center text-xs text-slate-400">
                Replies are generated by Gemini. Press Enter to send; Shift+Enter for a new line.
            </p>
        </form>

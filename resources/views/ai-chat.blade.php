    <script>
        const endpoint = @json(route('ai-chat.send'));
        const csrfToken = @json(csrf_token());
        const chatForm = document.getElementById('chat-form');
        const messageInput = document.getElementById('message');
        const sendButton = document.getElementById('send-button');
        const messages = document.getElementById('messages');
        const welcome = document.getElementById('welcome');
        const history = [];

        function addMessage(role, text, tools = [], isError = false) {
            const row = document.createElement('article');
            row.className = role === 'user' ? 'flex justify-end' : 'flex justify-start';

            const bubble = document.createElement('div');
            bubble.className = role === 'user'
                ? 'max-w-[85%] whitespace-pre-wrap rounded-2xl rounded-br-md bg-violet-600 px-4 py-3 text-sm leading-6 text-white sm:max-w-[75%]'
                : `max-w-[95%] whitespace-pre-wrap rounded-2xl rounded-bl-md px-4 py-3 text-sm leading-6 sm:max-w-[85%] ${isError ? 'bg-rose-50 text-rose-700' : 'bg-slate-100 text-slate-800'}`;

            const reply = document.createElement('p');
            reply.textContent = text;
            bubble.append(reply);

            if (tools.length > 0) {
                const toolList = document.createElement('ul');
                toolList.className = 'mt-3 flex flex-wrap gap-2 whitespace-normal';

                for (const tool of tools) {
                    const item = document.createElement('li');
                    item.className = 'rounded-lg border border-violet-200 bg-white px-2 py-1 font-mono text-xs text-violet-700';
                    item.textContent = `${tool.name}(${JSON.stringify(tool.arguments)})`;
                    toolList.append(item);
                }

                bubble.append(toolList);
            }

            row.append(bubble);
            messages.append(row);
            messages.scrollTop = messages.scrollHeight;

            return row;
        }

        async function askAssistant(message) {
            const response = await fetch(endpoint, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'Accept': 'application/json',
                    'X-CSRF-TOKEN': csrfToken,
                },
                body: JSON.stringify({ message, history: history.slice(-20) }),
            });

            const payload = await response.json().catch(() => ({}));

            if (!response.ok) {
                throw new Error(payload.message ?? `The server returned HTTP ${response.status}.`);
            }

            return payload;
        }

        chatForm.addEventListener('submit', async event => {
            event.preventDefault();

            const message = messageInput.value.trim();

            if (!message || sendButton.disabled) {
                return;
            }

            welcome.hidden = true;
            addMessage('user', message);
            messageInput.value = '';
            sendButton.disabled = true;
            sendButton.textContent = '...';
            const status = addMessage('assistant', 'Thinking...');

            try {
                const result = await askAssistant(message);
                status.remove();
                addMessage('assistant', result.reply || '(No reply)', result.tools);

                if (result.reply) {
                    history.push({ role: 'user', content: message }, { role: 'assistant', content: result.reply });
                }
            } catch (error) {
                console.error('AI chat request failed.', error);
                status.remove();
                addMessage('assistant', error.message || 'Could not get a reply. Please try again.', [], true);
            } finally {
                sendButton.disabled = false;
                sendButton.textContent = 'Send';
                messageInput.focus();
            }
        });

        messageInput.addEventListener('keydown', event => {
            if (event.key === 'Enter' && !event.shiftKey) {
                event.preventDefault();
                chatForm.requestSubmit();
            }
        });
    </script>
@endsection
